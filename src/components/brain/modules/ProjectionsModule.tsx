const INV_COLORS = ['#6366F1', '#8B5CF6', '#06B6D4', '#10B981', '#F59E0B', '#EF4444', '#A78BFA', '#34D399', '#F97316', '#EC4899'];

function InvestmentSection({ client, accent }: { client: Client; accent: string }) {
  const state = useProjectionStore((s) => s.states[client.id]);
  const setInvestment = useProjectionStore((s) => s.setInvestment);
  const setDuration = useProjectionStore((s) => s.setDuration);
  const lines = state.investment;

  const totalMonthly = lines.reduce((s, l) => s + l.monthly, 0);
  const totalProject = lines.reduce((sum, l) => {
    const months = l.onlyMonths ? l.onlyMonths.length : state.durationMonths;
    return sum + l.monthly * months;
  }, 0);
  const outputs = calculateFunnel(state.funnel);
  const projectedRevenue = outputs.revenue * state.durationMonths;
  const roi = totalProject > 0 ? projectedRevenue / totalProject : 0;
  const adsInvestment = lines
    .filter((l) => /ads|meta|google|tiktok/i.test(l.category))
    .reduce((s, l) => s + l.monthly * (l.onlyMonths?.length ?? state.durationMonths), 0);
  const projectedRoas = adsInvestment > 0 ? projectedRevenue / adsInvestment : 0;
  const profit = projectedRevenue - totalProject;
  const avgMonthly = state.durationMonths > 0 ? totalProject / state.durationMonths : 0;

  const pieData = lines.map((l) => ({ name: l.category, value: l.monthly }));

  const updateLine = (id: string, patch: Partial<InvestmentLine>) => {
    setInvestment(client.id, lines.map((l) => (l.id === id ? { ...l, ...patch } : l)));
  };
  const addLine = () => {
    setInvestment(client.id, [
      ...lines,
      { id: `i_${Math.random().toString(36).slice(2, 6)}`, category: 'Nueva categoría', monthly: 0 },
    ]);
  };
  const removeLine = (id: string) => {
    setInvestment(client.id, lines.filter((l) => l.id !== id));
  };

  // Stacked bar data por mes
  const stackedData = Array.from({ length: state.durationMonths }).map((_, i) => {
    const monthIdx = i + 1;
    const row: Record<string, string | number> = { month: `M${monthIdx}` };
    let total = 0;
    for (const l of lines) {
      const active = !l.onlyMonths || l.onlyMonths.includes(monthIdx);
      row[l.category] = active ? l.monthly : 0;
      if (active) total += l.monthly;
    }
    row['__total'] = total;
    return row;
  });

  const monthlyTotals = stackedData.map((d) => d['__total'] as number);

  return (
    <div className="space-y-4">
      {/* Top: lista editable + donut */}
      <div className="grid grid-cols-1 lg:grid-cols-[1.4fr_1fr] gap-4">
        <div className="surface p-5">
          <header className="flex items-center justify-between mb-3">
            <h3 className="heading text-base font-bold">Inversión mensual desglosada</h3>
            <div className="flex items-center gap-2">
              <Input
                type="number"
                label="Meses del proyecto"
                value={state.durationMonths}
                onChange={(e) => setDuration(client.id, Math.max(1, Number(e.target.value)))}
                className="w-32"
              />
              <Button size="sm" variant="secondary" leftIcon={<Plus className="h-3.5 w-3.5" />} onClick={addLine}>
                Agregar línea
              </Button>
            </div>
          </header>
          <div className="space-y-2">
            {lines.map((l) => (
              <div key={l.id} className="grid grid-cols-[1.5fr_120px_auto] gap-2 items-center">
                <Input value={l.category} onChange={(e) => updateLine(l.id, { category: e.target.value })} />
                <Input
                  type="number"
                  value={l.monthly}
                  onChange={(e) => updateLine(l.id, { monthly: Number(e.target.value) })}
                  leftAdornment="$"
                />
                <button
                  onClick={() => removeLine(l.id)}
                  className="h-10 w-10 rounded-md text-text-muted hover:text-status-danger hover:bg-bg-elevated"
                  aria-label="Eliminar"
                >
                  <Trash2 className="h-4 w-4 mx-auto" />
                </button>
              </div>
            ))}
          </div>
        </div>

        <div className="surface p-5">
          <h3 className="heading text-base font-bold mb-3">% por categoría</h3>
          <div className="h-72">
            <ResponsiveContainer width="100%" height="100%">
              <PieChart>
                <Pie data={pieData} dataKey="value" nameKey="name" cx="50%" cy="50%" outerRadius={88} innerRadius={48}>
                  {pieData.map((_, i) => <Cell key={i} fill={INV_COLORS[i % INV_COLORS.length]} />)}
                </Pie>
                <RTooltip
                  content={({ active, payload }) => {
                    if (!active || !payload || !payload.length) return null;
                    const p = payload[0];
                    const pct = totalMonthly > 0 ? ((p.value as number) / totalMonthly) * 100 : 0;
                    return (
                      <div
                        className="text-xs px-3 py-2 rounded-md"
                        style={{
                          background: 'rgba(15,15,25,0.95)',
                          border: `1px solid ${accent}`,
                          color: '#FFFFFF',
                        }}
                      >
                        <strong>{p.name}</strong>: {formatCurrency(p.value as number)} ({pct.toFixed(1)}%)
                      </div>
                    );
                  }}
                />
                <Legend wrapperStyle={{ fontSize: 10, color: '#A0A0B4' }} />
              </PieChart>
            </ResponsiveContainer>
          </div>
        </div>
      </div>

      {/* Cards resumen */}
      <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-4 gap-3">
        <SummaryCard label="Inversión mensual promedio" value={formatCurrency(avgMonthly)} accent={accent} />
        <SummaryCard label="Inversión total del proyecto" value={formatCurrency(totalProject)} accent={accent} />
        <SummaryCard label="Facturación proyectada total" value={formatCurrency(projectedRevenue)} accent={accent} />
        <SummaryCard label="ROI estimado" value={`${roi.toFixed(2)}x`} accent={accent} highlight />
      </div>
      <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
        <SecondaryCard
          label="ROAS proyectado (solo ADS)"
          hint={`Facturación / inversión en ADS (${formatCurrency(adsInvestment)})`}
          value={`${projectedRoas.toFixed(2)}x`}
          positive={projectedRoas >= 2.5}
        />
        <SecondaryCard
          label="Ganancia estimada"
          hint="Facturación proyectada − inversión total del proyecto"
          value={formatCurrency(profit)}
          positive={profit > 0}
        />
      </div>

      {/* Stacked bar chart + tendencia */}
      <div className="surface p-5">
        <header className="mb-3">
          <h3 className="heading text-base font-bold">Inversión por mes</h3>
          <p className="text-[11px] text-text-muted">Barras apiladas por categoría + línea de tendencia del total mensual</p>
        </header>
        <div className="h-80">
          <ResponsiveContainer width="100%" height="100%">
            <ComposedChart data={stackedData}>
              <CartesianGrid stroke="rgba(255,255,255,0.06)" strokeDasharray="3 3" />
              <XAxis dataKey="month" stroke="#6B6B80" fontSize={11} />
              <YAxis stroke="#6B6B80" fontSize={11} />
              <RTooltip
                content={({ active, payload, label }) => {
                  if (!active || !payload || !payload.length) return null;
                  const total = payload.reduce((s, p) => s + (typeof p.value === 'number' ? p.value : 0), 0);
                  return (
                    <div
                      className="text-xs rounded-md px-3 py-2"
                      style={{ background: 'rgba(15,15,25,0.95)', border: `1px solid ${accent}`, color: '#FFFFFF', minWidth: 200 }}
                    >
                      <div className="font-semibold mb-1.5">{label}</div>
                      {payload
                        .filter((p) => p.dataKey !== '__total' && typeof p.value === 'number' && (p.value as number) > 0)
                        .map((p) => (
                          <div key={p.dataKey} className="flex items-center justify-between gap-3">
                            <span style={{ color: p.color as string }}>● {p.name}</span>
                            <span>{formatCurrency(p.value as number)}</span>
                          </div>
                        ))}
                      <div className="mt-1.5 pt-1.5 border-t border-white/15 flex justify-between font-semibold">
                        <span>Total</span><span style={{ color: accent }}>{formatCurrency(total - (total / 2 > 0 ? 0 : 0))}</span>
                      </div>
                    </div>
                  );
                }}
              />
              <Legend wrapperStyle={{ fontSize: 10, color: '#A0A0B4' }} />
              {lines.map((l, i) => (
                <Bar key={l.id} dataKey={l.category} stackId="inv" fill={INV_COLORS[i % INV_COLORS.length]} />
              ))}
              <Line type="monotone" dataKey="__total" stroke={accent} strokeWidth={2} dot={{ r: 3 }} name="Total mensual" />
            </ComposedChart>
          </ResponsiveContainer>
        </div>
      </div>

      {/* Tabla con totales por mes y por categoría */}
      <div className="surface p-5">
        <h3 className="heading text-base font-bold mb-3">Resumen por mes con totales</h3>
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="text-left text-[10px] uppercase tracking-wider text-text-muted border-b border-border-default bg-bg-elevated/40">
                <th className="py-2 pr-3 pl-2">Categoría</th>
                {Array.from({ length: state.durationMonths }).map((_, i) => (
                  <th key={i} className="py-2 px-2 text-right">M{i + 1}</th>
                ))}
                <th className="py-2 pl-3 pr-2 text-right" style={{ color: accent }}>Total</th>
              </tr>
            </thead>
            <tbody>
              {lines.map((l, idx) => {
                const rowTotal = Array.from({ length: state.durationMonths }).reduce<number>((sum, _, i) => {
                  const active = !l.onlyMonths || l.onlyMonths.includes(i + 1);
                  return sum + (active ? l.monthly : 0);
                }, 0);
                return (
                  <tr key={l.id} className={cn('border-b border-border-subtle/40', idx % 2 === 1 && 'bg-bg-elevated/15')}>
                    <td className="py-2 pr-3 pl-2 text-text-primary text-xs">
                      <span className="inline-block h-2 w-2 rounded-full mr-2" style={{ background: INV_COLORS[idx % INV_COLORS.length] }} />
                      {l.category}
                    </td>
                    {Array.from({ length: state.durationMonths }).map((_, i) => {
                      const active = !l.onlyMonths || l.onlyMonths.includes(i + 1);
                      return (
                        <td key={i} className={cn('py-2 px-2 text-right text-xs', active ? 'text-text-primary' : 'text-text-muted opacity-40')}>
                          {active ? formatCurrency(l.monthly) : '—'}
                        </td>
                      );
                    })}
                    <td className="py-2 pl-3 pr-2 text-right text-xs font-semibold" style={{ color: accent }}>
                      {formatCurrency(rowTotal)}
                    </td>
                  </tr>
                );
              })}
              {/* Fila TOTAL MES */}
              <tr className="border-t-2 font-bold" style={{ background: withAlpha(accent, 0.10), borderColor: withAlpha(accent, 0.35) }}>
                <td className="py-2.5 pr-3 pl-2 text-text-primary uppercase text-[10px] tracking-wider">Total mes</td>
                {monthlyTotals.map((t, i) => (
                  <td key={i} className="py-2.5 px-2 text-right text-xs text-text-primary">{formatCurrency(t)}</td>
                ))}
                <td className="py-2.5 pl-3 pr-2 text-right text-xs" style={{ color: accent }}>
                  {formatCurrency(totalProject)}
                </td>
              </tr>
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}

function SummaryCard({ label, value, accent, highlight }: { label: string; value: string; accent: string; highlight?: boolean }) {
  return (
    <div
      className="surface p-4"
      style={highlight ? { borderColor: withAlpha(accent, 0.35), boxShadow: `0 0 24px -10px ${accent}` } : undefined}
    >
      <div className="text-[10px] uppercase tracking-wider text-text-muted">{label}</div>
      <div className="kpi-number mt-1.5" style={highlight ? { color: accent } : undefined}>{value}</div>
    </div>
  );
}

function SecondaryCard({ label, hint, value, positive }: { label: string; hint: string; value: string; positive: boolean }) {
  const color = positive ? '#10B981' : '#EF4444';
  return (
    <div className="surface p-4" style={{ borderColor: `${color}55` }}>
      <div className="text-[10px] uppercase tracking-wider text-text-muted">{label}</div>
      <div className="text-2xl font-bold mt-1" style={{ color }}>{value}</div>
      <div className="text-[10px] text-text-muted mt-1">{hint}</div>
    </div>
  );
}


