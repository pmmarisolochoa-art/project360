function PhasesSection({ client, accent }: { client: Client; accent: string }) {
  const state = useProjectionStore((s) => s.states[client.id]);
  const setPhases = useProjectionStore((s) => s.setPhases);
  const phases = state.phases;
  const startDate = parseISO(
    (client.onboardingData.goals as { idealStartDate?: string } | undefined)?.idealStartDate ??
      new Date().toISOString().slice(0, 10),
  );
  const totalWeeks = Math.max(...phases.map((p) => p.endWeek));
  const [unit, setUnit] = useState<'weeks' | 'months'>('weeks');
  const [expandedPhases, setExpandedPhases] = useState<Set<string>>(new Set());
  const [expandedTasks, setExpandedTasks] = useState<Set<string>>(new Set());

  // % de avance de fase derivado de subtareas completadas
  const phaseProgress = (p: ProjectPhase) => {
    const all = p.tasks.flatMap((t) => t.subtasks);
    if (all.length === 0) return p.progress;
    const done = all.filter((s) => s.done).length;
    return Math.round((done / all.length) * 100);
  };

  const togglePhase = (id: string) => {
    setExpandedPhases((s) => {
      const n = new Set(s); n.has(id) ? n.delete(id) : n.add(id); return n;
    });
  };
  const toggleTask = (id: string) => {
    setExpandedTasks((s) => {
      const n = new Set(s); n.has(id) ? n.delete(id) : n.add(id); return n;
    });
  };

  const updatePhases = (next: ProjectPhase[]) => setPhases(client.id, next);

  const updateTaskInPhase = (phaseId: string, taskId: string, patch: Partial<import('@/types/projection').GanttTask>) => {
    updatePhases(phases.map((p) => p.id !== phaseId ? p : {
      ...p,
      tasks: p.tasks.map((t) => t.id === taskId ? { ...t, ...patch } : t),
    }));
  };
  const toggleSubtask = (phaseId: string, taskId: string, subId: string) => {
    updatePhases(phases.map((p) => p.id !== phaseId ? p : {
      ...p,
      tasks: p.tasks.map((t) => t.id !== taskId ? t : {
        ...t,
        subtasks: t.subtasks.map((s) => s.id === subId ? { ...s, done: !s.done } : s),
      }),
    }));
  };
  const addTaskToPhase = (phaseId: string) => {
    const phase = phases.find((p) => p.id === phaseId);
    if (!phase) return;
    updatePhases(phases.map((p) => p.id !== phaseId ? p : {
      ...p,
      tasks: [...p.tasks, { id: `gt_${Math.random().toString(36).slice(2,7)}`, name: 'Nueva tarea', startWeek: phase.startWeek, endWeek: phase.endWeek, status: 'not_started' as const, subtasks: [] }],
    }));
  };
  const addSubtaskToTask = (phaseId: string, taskId: string) => {
    updatePhases(phases.map((p) => p.id !== phaseId ? p : {
      ...p,
      tasks: p.tasks.map((t) => t.id !== taskId ? t : {
        ...t,
        subtasks: [...t.subtasks, { id: `gs_${Math.random().toString(36).slice(2,7)}`, name: 'Nueva subtarea', done: false }],
      }),
    }));
  };

  const headerLabels = unit === 'weeks'
    ? Array.from({ length: totalWeeks }).map((_, i) => i + 1)
    : Array.from({ length: Math.ceil(totalWeeks / 4) }).map((_, i) => i + 1);

  const colorFor = (status: ProjectPhase['status']) =>
    status === 'in_progress' ? accent : PHASE_STATUS_COLOR[status];

  return (
    <div className="surface p-5">
      <header className="flex items-center justify-between mb-4 flex-wrap gap-3">
        <div>
          <h3 className="heading text-base font-bold">Tiempos de ejecución por fases</h3>
          <p className="text-[11px] text-text-muted">
            {phases.length} fases · {totalWeeks} semanas · inicio {format(startDate, 'd MMM yyyy', { locale: es })}
          </p>
        </div>
        <div className="inline-flex rounded-[10px] border border-border-subtle bg-bg-base/40 p-0.5">
          <button onClick={() => setUnit('weeks')} className={cn('px-3 py-1.5 rounded-md text-xs', unit === 'weeks' ? 'bg-bg-elevated text-text-primary' : 'text-text-secondary')}>
            Semanas
          </button>
          <button onClick={() => setUnit('months')} className={cn('px-3 py-1.5 rounded-md text-xs', unit === 'months' ? 'bg-bg-elevated text-text-primary' : 'text-text-secondary')}>
            Meses
          </button>
        </div>
      </header>

      <div className="overflow-x-auto">
        <div className="min-w-[900px]">
          {/* Header de timeline */}
          <div className="grid grid-cols-[280px_1fr] gap-2 mb-2 sticky top-0 bg-bg-surface z-10">
            <div className="text-[10px] uppercase tracking-wider text-text-muted px-2">Fase / Tarea / Subtarea</div>
            <div className="grid gap-px text-[9px] text-text-muted" style={{ gridTemplateColumns: `repeat(${headerLabels.length}, minmax(0, 1fr))` }}>
              {headerLabels.map((n, i) => (
                <div key={i} className="text-center font-mono">
                  {unit === 'weeks' ? (((i+1) % 4 === 0 || i === 0 || i === headerLabels.length - 1) ? `S${n}` : '') : `M${n}`}
                </div>
              ))}
            </div>
          </div>

          {phases.map((p) => {
            const progress = phaseProgress(p);
            const open = expandedPhases.has(p.id);
            const span = p.endWeek - p.startWeek + 1;
            const ratio = (w: number) => ((w - 1) / totalWeeks) * 100;

            return (
              <div key={p.id} className="border-b border-border-subtle/40 py-1">
                {/* PHASE ROW */}
                <div className="grid grid-cols-[280px_1fr] gap-2 items-center group">
                  <div className="flex items-center gap-1 min-w-0 px-1 py-1 bg-bg-elevated/30 rounded-md">
                    <button onClick={() => togglePhase(p.id)} className="text-text-muted hover:text-text-primary shrink-0">
                      {open ? <ChevronDown className="h-3.5 w-3.5" /> : <ChevronUp className="h-3.5 w-3.5" />}
                    </button>
                    <div className="min-w-0 flex-1">
                      <div className="text-sm font-bold text-text-primary truncate" title={p.name}>{p.name}</div>
                      <div className="flex items-center gap-2 text-[9px] text-text-muted">
                        <span style={{ color: colorFor(p.status) }}>{PHASE_STATUS_LABEL[p.status]}</span>
                        <span>· {progress}%</span>
                        <span>· S{p.startWeek}–{p.endWeek}</span>
                      </div>
                    </div>
                    <button onClick={() => addTaskToPhase(p.id)} className="opacity-0 group-hover:opacity-100 text-text-muted hover:text-text-primary shrink-0" title="Agregar tarea">
                      <Plus className="h-3.5 w-3.5" />
                    </button>
                  </div>
                  <div className="relative h-3 rounded-md bg-bg-elevated/30">
                    <div
                      className="absolute top-0 bottom-0 rounded-md"
                      style={{
                        left: `${ratio(p.startWeek)}%`,
                        width: `${(span / totalWeeks) * 100}%`,
                        background: `linear-gradient(90deg, ${accent}, ${withAlpha(accent, 0.5)})`,
                        boxShadow: `0 0 10px -4px ${accent}`,
                      }}
                      title={`${p.name} · ${format(addWeeks(startDate, p.startWeek - 1), 'd MMM', { locale: es })} – ${format(addWeeks(startDate, p.endWeek - 1), 'd MMM', { locale: es })}`}
                    />
                  </div>
                </div>

                {/* TASKS */}
                {open && p.tasks.map((t) => {
                  const tOpen = expandedTasks.has(t.id);
                  const tSpan = t.endWeek - t.startWeek + 1;
                  const tColor = colorFor(t.status);
                  const tDone = t.subtasks.length > 0 ? t.subtasks.filter((s) => s.done).length : 0;
                  return (
                    <div key={t.id} className="ml-2">
                      <div className="grid grid-cols-[280px_1fr] gap-2 items-center group">
                        <div className="flex items-center gap-1 min-w-0 pl-4 py-1">
                          <button onClick={() => toggleTask(t.id)} className="text-text-muted hover:text-text-primary shrink-0">
                            {tOpen ? <ChevronDown className="h-3 w-3" /> : <ChevronUp className="h-3 w-3" />}
                          </button>
                          <div className="min-w-0 flex-1">
                            <div className="text-xs text-text-primary truncate" title={t.name}>{t.name}</div>
                            {t.subtasks.length > 0 && (
                              <div className="text-[9px] text-text-muted">{tDone}/{t.subtasks.length} subtareas</div>
                            )}
                          </div>
                          <button onClick={() => addSubtaskToTask(p.id, t.id)} className="opacity-0 group-hover:opacity-100 text-text-muted hover:text-text-primary shrink-0" title="Agregar subtarea">
                            <Plus className="h-3 w-3" />
                          </button>
                        </div>
                        <div className="relative h-2 rounded-md bg-bg-elevated/30">
                          <div
                            className="absolute top-0 bottom-0 rounded-md"
                            style={{
                              left: `${ratio(t.startWeek)}%`,
                              width: `${(tSpan / totalWeeks) * 100}%`,
                              background: tColor,
                            }}
                            title={`${t.name} · S${t.startWeek}–${t.endWeek} · ${PHASE_STATUS_LABEL[t.status]}`}
                          />
                        </div>
                      </div>

                      {/* SUBTASKS */}
                      {tOpen && t.subtasks.map((s) => {
                        return (
                          <div key={s.id} className="grid grid-cols-[280px_1fr] gap-2 items-center pl-10 py-0.5">
                            <label className="flex items-center gap-2 text-[11px] text-text-secondary cursor-pointer">
                              <input
                                type="checkbox"
                                checked={s.done}
                                onChange={() => toggleSubtask(p.id, t.id, s.id)}
                                className="h-3 w-3 accent-accent-violet"
                              />
                              <span className={cn('truncate', s.done && 'line-through text-text-muted')}>{s.name}</span>
                            </label>
                            <div className="relative h-1 rounded bg-bg-elevated/30">
                              <div
                                className="absolute top-0 bottom-0 rounded"
                                style={{
                                  left: `${ratio(t.startWeek)}%`,
                                  width: `${(tSpan / totalWeeks) * 100}%`,
                                  background: s.done ? '#10B981' : withAlpha(tColor, 0.4),
                                }}
                              />
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  );
                })}
              </div>
            );
          })}
        </div>
      </div>

      <div className="mt-4 flex items-center gap-3 flex-wrap text-[10px] text-text-muted">
        {(Object.keys(PHASE_STATUS_LABEL) as ProjectPhase['status'][]).map((s) => (
          <div key={s} className="flex items-center gap-1">
            <span className="h-2 w-3 rounded-sm" style={{ background: colorFor(s) }} />
            {PHASE_STATUS_LABEL[s]}
          </div>
        ))}
      </div>
    </div>
  );
}

/* ═══════════════════════════════════════════════════════════════════════════
   D — VS MERCADO (benchmarks + sizing)
   ═══════════════════════════════════════════════════════════════════════════ */

function MarketSection({ client, accent }: { client: Client; accent: string }) {
  const bench = getBenchmark(client.industry);
  const state = useProjectionStore((s) => s.states[client.id]);
  const patchMarket = useProjectionStore((s) => s.patchMarket);
  const setOverride = useProjectionStore((s) => s.setBenchmarkOverride);
  const outputs = calculateFunnel(state.funnel);

  const rows = useMemo(() => [
    { key: 'ctrMeta',     label: 'CTR Meta Ads',       unit: '%', benchmark: bench.ctrMeta,     yours: state.funnel.ctr * 100,                higherBetter: true },
    { key: 'ctrGoogle',   label: 'CTR Google Ads',     unit: '%', benchmark: bench.ctrGoogle,   yours: state.funnel.ctr * 100,                higherBetter: true },
    { key: 'landingConv', label: 'Conversión landing', unit: '%', benchmark: bench.landingConv, yours: state.funnel.landingConversionRate * 100, higherBetter: true },
    { key: 'avgCpl',      label: 'CPL',                unit: '$', benchmark: bench.avgCpl,      yours: outputs.cpl,                            higherBetter: false },
    { key: 'avgRoas',     label: 'ROAS',               unit: 'x', benchmark: bench.avgRoas,     yours: outputs.roas,                            higherBetter: true },
    { key: 'closeRate',   label: 'Tasa de cierre',     unit: '%', benchmark: bench.closeRate,   yours: state.funnel.closeRate * 100,           higherBetter: true },
    { key: 'avgLtv',      label: 'LTV',                unit: '$', benchmark: bench.avgLtv,      yours: state.funnel.averageTicket,             higherBetter: true },
  ], [bench, state.funnel, outputs]);

  // Aplica override
  const rowsResolved = rows.map((r) => {
    const overridden = state.benchmarksOverride[r.key];
    const benchValue = overridden ?? r.benchmark;
    const diff = r.higherBetter ? ((r.yours - benchValue) / benchValue) * 100 : ((benchValue - r.yours) / benchValue) * 100;
    const status: 'excellent' | 'good' | 'improve' | 'critical' =
      diff >= 25 ? 'excellent' : diff >= 0 ? 'good' : diff >= -25 ? 'improve' : 'critical';
    return { ...r, benchValue, diff, status };
  });

  const statusMeta: Record<'excellent' | 'good' | 'improve' | 'critical', { label: string; tone: 'success' | 'info' | 'warning' | 'danger'; color: string }> = {
    excellent: { label: 'Excelente', tone: 'success', color: '#10B981' },
    good:      { label: 'Bien',      tone: 'info',    color: '#06B6D4' },
    improve:   { label: 'Mejorar',   tone: 'warning', color: '#F59E0B' },
    critical:  { label: 'Crítico',   tone: 'danger',  color: '#EF4444' },
  };

  const overallScore = Math.round(
    rowsResolved.reduce((s, r) => s + Math.max(0, Math.min(100, 50 + r.diff / 2)), 0) / rowsResolved.length,
  );

  // Datos para radar: normaliza cada métrica a 0..100 contra benchmark
  const radarData = rowsResolved.slice(0, 6).map((r) => {
    const youNorm = r.higherBetter
      ? Math.min(150, (r.yours / r.benchValue) * 100)
      : Math.min(150, (r.benchValue / Math.max(0.0001, r.yours)) * 100);
    return {
      metric: r.label,
      Tu_proyeccion: Math.max(0, Math.round(youNorm)),
      Benchmark: 100,
    };
  });

  const sizing = state.market;
  const som = (sizing.sam * sizing.somPercent) / 100;
  const shareYear1 = sizing.sam > 0 ? (outputs.sales * 12 / sizing.sam) * 100 : 0;

  return (
    <div className="space-y-4">
      {/* PARTE A — Scorecard */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3">
        {rowsResolved.slice(0, 4).map((r) => {
          const meta = statusMeta[r.status];
          const pct = r.higherBetter
            ? Math.min(150, (r.yours / r.benchValue) * 100)
            : Math.min(150, (r.benchValue / Math.max(0.0001, r.yours)) * 100);
          return (
            <div key={r.key} className="surface p-4">
              <div className="text-[10px] uppercase tracking-wider text-text-muted">{r.label}</div>
              <div className="flex items-baseline gap-2 mt-1">
                <span className="kpi-number" style={{ color: meta.color }}>
                  {r.unit === '$' ? `$${r.yours.toFixed(2)}` : `${r.yours.toFixed(2)}${r.unit}`}
                </span>
                {r.diff >= 0 ? <ArrowUp className="h-3.5 w-3.5 text-status-success" /> : <ArrowDown className="h-3.5 w-3.5 text-status-danger" />}
              </div>
              <div className="text-[10px] text-text-muted mt-1">
                Benchmark: {r.unit === '$' ? `$${r.benchValue.toFixed(2)}` : `${r.benchValue.toFixed(2)}${r.unit}`}
              </div>
              <div className="mt-2 h-1.5 rounded-full bg-bg-elevated overflow-hidden relative">
                <div
                  className="absolute top-0 bottom-0 left-0 rounded-full"
                  style={{ width: `${Math.min(100, pct)}%`, background: meta.color }}
                />
                {pct > 100 && (
                  <div
                    className="absolute top-0 bottom-0 rounded-full"
                    style={{ left: '100%', width: `${Math.min(50, pct - 100)}%`, background: '#10B981', opacity: 0.6 }}
                  />
                )}
              </div>
            </div>
          );
        })}
      </div>

      {/* PARTE B — Radar */}
      <div className="surface p-5">
        <header className="mb-3">
          <h3 className="heading text-base font-bold">Posición competitiva proyectada</h3>
          <p className="text-[11px] text-text-muted">Tu proyección vs benchmark de {client.industry} (100 = benchmark)</p>
        </header>
        <div className="h-80">
          <ResponsiveContainer width="100%" height="100%">
            <RadarChart data={radarData}>
              <PolarGrid stroke="rgba(255,255,255,0.08)" />
              <PolarAngleAxis dataKey="metric" tick={{ fill: '#A0A0B4', fontSize: 10 }} />
              <PolarRadiusAxis tick={{ fill: '#6B6B80', fontSize: 9 }} angle={90} domain={[0, 150]} />
              <Radar name="Benchmark" dataKey="Benchmark" stroke="#A0A0B4" fill="#A0A0B4" fillOpacity={0.18} />
              <Radar name="Tu proyección" dataKey="Tu_proyeccion" stroke={accent} fill={accent} fillOpacity={0.30} />
              <Legend wrapperStyle={{ fontSize: 11, color: '#A0A0B4' }} />
              <RTooltip
                contentStyle={{ background: 'rgba(15,15,25,0.95)', border: `1px solid ${accent}`, borderRadius: 10, fontSize: 12, color: '#FFFFFF' }}
              />
            </RadarChart>
          </ResponsiveContainer>
        </div>
      </div>

      {/* PARTE C — Tabla detallada */}
      <div className="surface p-5">
        <header className="flex items-center justify-between mb-3">
          <div>
            <h3 className="heading text-base font-bold">Detalle por métrica</h3>
            <p className="text-[11px] text-text-muted">Edita los benchmarks si tienes data más reciente</p>
          </div>
          <div className="rounded-[10px] border px-3 py-2 text-center" style={{ borderColor: accent, background: withAlpha(accent, 0.10) }}>
            <div className="text-[10px] uppercase tracking-wider text-text-muted">Posición general</div>
            <div className="text-lg font-bold" style={{ color: accent }}>{overallScore}/100</div>
          </div>
        </header>
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="text-left text-[10px] uppercase tracking-wider text-text-muted border-b border-border-default bg-bg-elevated/40">
                <th className="py-2 pl-2 pr-3">Métrica</th>
                <th className="py-2 pr-3 text-right">Benchmark</th>
                <th className="py-2 pr-3 text-right">Tu proyección</th>
                <th className="py-2 pr-3 text-right">Diferencia</th>
                <th className="py-2 pr-3 pr-2 text-center">Estado</th>
              </tr>
            </thead>
            <tbody>
              {rowsResolved.map((r, idx) => {
                const meta = statusMeta[r.status];
                return (
                  <tr key={r.key} className={cn('border-b border-border-subtle/30', idx % 2 === 1 && 'bg-bg-elevated/15')}>
                    <td className="py-2.5 pl-2 pr-3 text-text-primary">{r.label}</td>
                    <td className="py-2.5 pr-3 text-right">
                      <input
                        type="number"
                        defaultValue={r.benchValue}
                        step="0.1"
                        onBlur={(e) => {
                          const v = Number(e.target.value);
                          setOverride(client.id, r.key, v === r.benchmark ? undefined : v);
                        }}
                        className="w-24 bg-bg-elevated/40 border border-border-subtle rounded-md px-2 py-1 text-right text-text-primary outline-none text-xs"
                      />
                    </td>
                    <td className="py-2.5 pr-3 text-right font-semibold text-text-primary">
                      {r.unit === '$' ? `$${r.yours.toFixed(2)}` : `${r.yours.toFixed(2)}${r.unit}`}
                    </td>
                    <td className="py-2.5 pr-3 text-right font-semibold" style={{ color: r.diff >= 0 ? '#10B981' : '#EF4444' }}>
                      {r.diff >= 0 ? '+' : ''}{r.diff.toFixed(0)}%
                    </td>
                    <td className="py-2.5 pl-3 pr-2 text-center">
                      <Badge tone={meta.tone}>{meta.label}</Badge>
                    </td>
                  </tr>
                );
              })}
              <tr className="border-t-2 font-bold" style={{ background: withAlpha(accent, 0.10), borderColor: withAlpha(accent, 0.35) }}>
                <td className="py-2.5 pl-2 pr-3 text-text-primary uppercase text-[10px] tracking-wider">Posición general</td>
                <td colSpan={3} className="py-2.5 pr-3 text-right text-xs text-text-muted">Promedio ponderado</td>
                <td className="py-2.5 pl-3 pr-2 text-center" style={{ color: accent }}>{overallScore}/100</td>
              </tr>
            </tbody>
          </table>
        </div>
      </div>

      <div className="surface p-5">
        <h3 className="heading text-base font-bold mb-3">Tamaño de mercado</h3>
        <div className="grid grid-cols-1 md:grid-cols-4 gap-3">
          <Input label="TAM (mercado total)" type="number" value={sizing.tam}
            onChange={(e) => patchMarket(client.id, { tam: Number(e.target.value) })} />
          <Input label="SAM (serviceable)" type="number" value={sizing.sam}
            onChange={(e) => patchMarket(client.id, { sam: Number(e.target.value) })} />
          <Input label="SOM (% del SAM)" type="number" step="0.1" value={sizing.somPercent}
            onChange={(e) => patchMarket(client.id, { somPercent: Number(e.target.value) })} />
          <div className="rounded-[10px] border bg-bg-base/30 p-3" style={{ borderColor: withAlpha(accent, 0.25) }}>
            <div className="text-[10px] uppercase tracking-wider text-text-muted">SOM calculado</div>
            <div className="text-lg font-bold" style={{ color: accent }}>{formatNumber(Math.round(som))} personas</div>
            <div className="text-[10px] text-text-muted mt-1">Cuota proyectada año 1: {shareYear1.toFixed(2)}%</div>
          </div>
        </div>
      </div>
    </div>
  );
}

/* ═══════════════════════════════════════════════════════════════════════════
   E — OKRs
   ═══════════════════════════════════════════════════════════════════════════ */

function OkrsSection({ client, accent }: { client: Client; accent: string }) {
  const state = useProjectionStore((s) => s.states[client.id]);
  const setOkrs = useProjectionStore((s) => s.setOkrs);
  const setSuccessIndicators = useProjectionStore((s) => s.setSuccessIndicators);
  const okrs = state.okrs;

  const updateOkr = (id: string, patch: Partial<OKR>) => {
    setOkrs(client.id, okrs.map((o) => (o.id === id ? { ...o, ...patch } : o)));
  };
  const updateKr = (okrId: string, krId: string, patch: Partial<KeyResult>) => {
    setOkrs(client.id, okrs.map((o) =>
      o.id !== okrId ? o : { ...o, keyResults: o.keyResults.map((k) => (k.id === krId ? { ...k, ...patch } : k)) },
    ));
  };
  const addKr = (okrId: string) => {
    setOkrs(client.id, okrs.map((o) =>
      o.id !== okrId ? o : {
        ...o,
        keyResults: [
          ...o.keyResults,
          { id: `kr_${Math.random().toString(36).slice(2, 6)}`, description: 'Nuevo Key Result', initialValue: 0, targetValue: 100, currentValue: 0, unit: 'count' },
        ].slice(0, 5),
      },
    ));
  };
  const removeKr = (okrId: string, krId: string) => {
    setOkrs(client.id, okrs.map((o) =>
      o.id !== okrId ? o : { ...o, keyResults: o.keyResults.filter((k) => k.id !== krId) },
    ));
  };

  return (
    <div className="space-y-4">
      {okrs.map((okr) => (
        <div key={okr.id} className="surface p-5">
          <div className="flex items-start gap-3 mb-4">
            <div
              className="h-9 w-9 rounded-[10px] flex items-center justify-center heading font-bold text-lg shrink-0"
              style={{ background: withAlpha(accent, 0.15), color: accent }}
            >
              O
            </div>
            <div className="flex-1 space-y-2">
              <Textarea
                rows={2}
                value={okr.objective}
                onChange={(e) => updateOkr(okr.id, { objective: e.target.value })}
                placeholder="Objetivo principal del proyecto…"
              />
              <div className="grid grid-cols-2 gap-3">
                <Input label="Deadline" type="date" value={okr.deadline} onChange={(e) => updateOkr(okr.id, { deadline: e.target.value })} />
                <Input label="Responsable" value={okr.responsible} onChange={(e) => updateOkr(okr.id, { responsible: e.target.value })} />
              </div>
            </div>
          </div>

          <div className="space-y-3">
            {okr.keyResults.map((kr) => (
              <KrCard
                key={kr.id}
                kr={kr}
                accent={accent}
                duration={state.durationMonths}
                onChange={(patch) => updateKr(okr.id, kr.id, patch)}
                onRemove={() => removeKr(okr.id, kr.id)}
                hasAdsData={Object.values(client.adsConnected).some(Boolean)}
              />
            ))}
            <button
              onClick={() => addKr(okr.id)}
              disabled={okr.keyResults.length >= 5}
              className="w-full rounded-[10px] border border-dashed border-border-default py-2 text-xs text-text-secondary hover:text-text-primary hover:bg-bg-elevated transition disabled:opacity-50"
            >
              <Plus className="h-3.5 w-3.5 inline mr-1" /> Agregar Key Result (máx 5)
            </button>
          </div>
        </div>
      ))}

      {/* Indicadores de éxito */}
      <div className="surface p-5">
        <h3 className="heading text-base font-bold mb-1">Indicadores de Éxito</h3>
        <p className="text-[11px] text-text-muted mb-3">¿Cómo sabremos que el proyecto fue un éxito?</p>
        <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
          {[0, 1, 2].map((i) => (
            <Textarea
              key={i}
              rows={3}
              value={state.successIndicators[i] ?? ''}
              onChange={(e) => {
                const next = [...state.successIndicators];
                next[i] = e.target.value;
                setSuccessIndicators(client.id, next);
              }}
            />
          ))}
        </div>
      </div>
    </div>
  );
}

function KrCard({
  kr, accent, duration, onChange, onRemove, hasAdsData,
}: {
  kr: KeyResult;
  accent: string;
  duration: number;
  onChange: (patch: Partial<KeyResult>) => void;
  onRemove: () => void;
  hasAdsData: boolean;
}) {
  const [linkModalOpen, setLinkModalOpen] = useState(false);

  const progress = kr.targetValue !== kr.initialValue
    ? Math.max(0, Math.min(100, ((kr.currentValue - kr.initialValue) / (kr.targetValue - kr.initialValue)) * 100))
    : 0;

  const linkedLabel = kr.linkedToMetric ? AD_METRIC_LABEL[kr.linkedToMetric] : null;
  const hasRealData = !!(kr.linkedToMetric && hasAdsData);

  // Genera línea de proyección lineal del valor inicial al objetivo
  const projectionData = Array.from({ length: duration }).map((_, i) => {
    const frac = (i + 1) / duration;
    const projected = kr.initialValue + (kr.targetValue - kr.initialValue) * frac;
    const actual = kr.monthlyActuals?.[i];
    return { month: `M${i + 1}`, projected: Math.round(projected * 100) / 100, actual };
  });
  const showActuals = (kr.monthlyActuals?.length ?? 0) > 0;

  return (
    <div className="rounded-[10px] border border-border-subtle bg-bg-base/30 p-3">
      {/* Header */}
      <div className="flex items-start gap-3 mb-3">
        <div
          className="h-7 w-7 rounded-md flex items-center justify-center text-xs font-bold shrink-0"
          style={{ background: withAlpha(accent, 0.12), color: accent }}
        >
          KR
        </div>
        <div className="flex-1 min-w-0">
          {/* Descripción full-width sin truncar */}
          <input
            value={kr.description}
            onChange={(e) => onChange({ description: e.target.value })}
            placeholder="Descripción del Key Result"
            className="w-full bg-bg-elevated/40 border border-border-subtle rounded-md px-3 py-2 text-sm text-text-primary outline-none focus:border-accent-violet/60"
            style={{ caretColor: accent }}
          />
          {linkedLabel && (
            <div className="mt-2">
              <span
                className="inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider"
                style={{
                  background: hasRealData ? 'rgba(16,185,129,0.12)' : 'rgba(160,160,180,0.12)',
                  color: hasRealData ? '#10B981' : '#A0A0B4',
                  border: `1px solid ${hasRealData ? 'rgba(16,185,129,0.3)' : 'rgba(160,160,180,0.3)'}`,
                }}
              >
                <Link2 className="h-2.5 w-2.5" /> Vinculado a {linkedLabel}
              </span>
            </div>
          )}
        </div>
        <button
          onClick={onRemove}
          className="h-9 w-9 rounded-md text-text-muted hover:text-status-danger hover:bg-bg-elevated"
          aria-label="Eliminar"
        >
          <Trash2 className="h-4 w-4 mx-auto" />
        </button>
      </div>

      {/* Valores y acción */}
      <div className="grid grid-cols-1 md:grid-cols-5 gap-2 mb-3">
        <Input label="Inicial" type="number" value={kr.initialValue} onChange={(e) => onChange({ initialValue: Number(e.target.value) })} />
        <div>
          <label className="text-xs font-medium text-text-secondary mb-1.5 block">Actual</label>
          {hasRealData ? (
            <div className="h-10 rounded-md border bg-bg-elevated/40 px-3 flex items-center text-sm" style={{ borderColor: 'rgba(16,185,129,0.4)' }}>
              <span className="text-status-success">{kr.currentValue}</span>
            </div>
          ) : kr.linkedToMetric ? (
            <div className="h-10 rounded-md border border-border-subtle bg-bg-base/30 px-3 flex items-center text-sm text-text-muted italic">
              Sin datos aún
            </div>
          ) : (
            <input
              type="number"
              value={kr.currentValue}
              onChange={(e) => onChange({ currentValue: Number(e.target.value) })}
              className="w-full h-10 rounded-md border border-border-subtle bg-bg-surface px-3 text-sm text-text-primary outline-none focus:border-accent-violet/60"
            />
          )}
        </div>
        <Input label="Meta" type="number" value={kr.targetValue} onChange={(e) => onChange({ targetValue: Number(e.target.value) })} />
        <Select label="Unidad" value={kr.unit} options={[
          { value: 'USD', label: 'USD' }, { value: '%', label: '%' }, { value: 'count', label: 'Conteo' }, { value: 'ROAS', label: 'ROAS' },
        ]} onChange={(e) => onChange({ unit: e.target.value as KeyResult['unit'] })} />
        <div>
          <div className="text-xs font-medium text-text-secondary mb-1.5">Acción</div>
          <button
            onClick={() => setLinkModalOpen(true)}
            className="w-full h-10 rounded-md border border-border-subtle text-xs text-text-secondary hover:text-text-primary hover:bg-bg-elevated inline-flex items-center justify-center gap-1"
            title="Vincular a métrica del módulo ADS"
          >
            <Link2 className="h-3.5 w-3.5" /> {kr.linkedToMetric ? 'Cambiar' : 'Vincular ADS'}
          </button>
        </div>
      </div>

      {/* Progreso */}
      <div className="h-2 rounded-full bg-bg-elevated overflow-hidden">
        <div
          className="h-full rounded-full"
          style={{ width: `${progress}%`, background: `linear-gradient(90deg, ${accent}, ${withAlpha(accent, 0.5)})` }}
        />
      </div>
      <div className="text-[10px] text-text-muted text-right mt-1">{progress.toFixed(0)}% completado</div>

      {/* Mini-gráfica proyectado vs real (solo si hay KR vinculado) */}
      {kr.linkedToMetric && (
        <div className="mt-3 rounded-md border border-border-subtle bg-bg-base/20 p-2">
          <div className="flex items-center justify-between mb-1">
            <span className="text-[10px] uppercase tracking-wider text-text-muted">Proyectado vs Real</span>
            {!showActuals && (
              <span className="text-[10px] text-text-muted italic">
                Agrega datos reales en módulo Métricas
              </span>
            )}
          </div>
          <div className="h-20">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart data={projectionData}>
                <XAxis dataKey="month" hide />
                <YAxis hide />
                <RTooltip
                  content={({ active, payload, label }) => {
                    if (!active || !payload || !payload.length) return null;
                    return (
                      <div className="text-[10px] rounded-md px-2 py-1" style={{ background: 'rgba(15,15,25,0.95)', border: `1px solid ${accent}`, color: '#FFFFFF' }}>
                        <div className="font-semibold mb-0.5">{label}</div>
                        {payload.map((p) => (
                          <div key={p.dataKey} className="flex justify-between gap-3">
                            <span style={{ color: p.color as string }}>{p.dataKey === 'projected' ? 'Proyectado' : 'Real'}</span>
                            <span>{p.value !== null && p.value !== undefined ? Number(p.value).toFixed(2) : '—'}</span>
                          </div>
                        ))}
                      </div>
                    );
                  }}
                />
                <Line type="monotone" dataKey="projected" stroke={withAlpha(accent, 0.55)} strokeWidth={1.5} strokeDasharray="4 4" dot={false} />
                {showActuals && <Line type="monotone" dataKey="actual" stroke={accent} strokeWidth={2} dot={{ r: 2 }} />}
              </LineChart>
            </ResponsiveContainer>
          </div>
        </div>
      )}

      {linkModalOpen && (
        <Modal
          open
          onClose={() => setLinkModalOpen(false)}
          size="sm"
          title="Vincular métrica de ADS"
          footer={
            <>
              <Button variant="ghost" size="sm" onClick={() => setLinkModalOpen(false)}>Cancelar</Button>
              {kr.linkedToMetric && (
                <Button variant="danger" size="sm" onClick={() => { onChange({ linkedToMetric: undefined }); setLinkModalOpen(false); toast.info('KR desvinculado'); }}>
                  Desvincular
                </Button>
              )}
            </>
          }
        >
          <p className="text-sm text-text-secondary mb-3">¿Qué métrica de ADS representa este KR?</p>
          <div className="grid grid-cols-2 gap-2">
            {(Object.keys(AD_METRIC_LABEL) as AdMetricKind[]).map((m) => (
              <button
                key={m}
                onClick={() => { onChange({ linkedToMetric: m }); setLinkModalOpen(false); toast.success(`Vinculado a ${AD_METRIC_LABEL[m]}`); }}
                className={cn(
                  'rounded-md border px-3 py-2 text-sm text-left transition',
                  kr.linkedToMetric === m
                    ? 'border-accent-violet/50 bg-accent-violet/10 text-text-primary'
                    : 'border-border-subtle bg-bg-elevated/30 text-text-secondary hover:text-text-primary hover:bg-bg-elevated',
                )}
              >
                {AD_METRIC_LABEL[m]}
              </button>
            ))}
          </div>
        </Modal>
      )}
    </div>
  );
}

