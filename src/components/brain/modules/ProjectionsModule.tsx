export function ProjectionsModule({ client }: { client: Client }) {
  const accent = client.primaryColor;
  const ensure = useProjectionStore((s) => s.ensure);
  const state = useProjectionStore((s) => s.states[client.id]);
  const [exporting, setExporting] = useState(false);
  const [active, setActive] = useState<SubTab>('summary');

  useEffect(() => {
    ensure(client.id, {
      projectType: client.projectType,
      funnel: {
        monthlyAdsBudget: client.monthlyAdsBudget,
        averageTicket: (client.onboardingData.business as { averageTicket?: number } | undefined)?.averageTicket ?? 0,
      } as Partial<FunnelInputs> as never,
      debriefing: {
        executiveSummary: client.aiBrainData.executiveSummary
          ? { text: client.aiBrainData.executiveSummary, autoGenerated: true }
          : undefined,
        valueProp: client.aiBrainData.irresistibleOffer
          ? { text: client.aiBrainData.irresistibleOffer, bigIdea: '', guarantees: '' }
          : undefined,
      },
    });
  }, [client.id, client.monthlyAdsBudget, client.projectType, client.aiBrainData.executiveSummary, client.aiBrainData.irresistibleOffer, client.onboardingData.business, ensure]);

  if (!state) return null;

  const handleExport = async () => {
    setExporting(true);
    try {
      await exportProjectionToPdf({ client, state });
      toast.success('PDF descargado');
    } catch (e) {
      console.error(e);
      toast.error('No pudimos generar el PDF');
    } finally {
      setExporting(false);
    }
  };

  return (
    <div className="space-y-4">
      {/* Header con tabs internos + botón PDF */}
      <div className="flex items-center justify-between gap-3 flex-wrap">
        <div className="surface p-1 flex items-center gap-0.5 overflow-x-auto">
          {SUB_TABS.map((t) => {
            const isActive = active === t.id;
            return (
              <button
                key={t.id}
                onClick={() => setActive(t.id)}
                className={cn(
                  'inline-flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-xs whitespace-nowrap transition focus-ring',
                  isActive ? 'text-text-primary' : 'text-text-secondary hover:text-text-primary',
                )}
                style={isActive ? { background: withAlpha(accent, 0.18) } : undefined}
              >
                <span className="text-[10px] font-mono text-text-muted">{t.letter}</span>
                <t.icon className="h-3.5 w-3.5" />
                <span className="font-medium">{t.label}</span>
              </button>
            );
          })}
        </div>
        <Button
          leftIcon={<Download className="h-4 w-4" />}
          loading={exporting}
          onClick={handleExport}
        >
          Descargar PDF
        </Button>
      </div>

      <motion.div
        key={active}
        initial={{ opacity: 0, y: 6 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.25 }}
      >
        {active === 'summary'    && <SummarySection client={client} accent={accent} />}
        {active === 'funnel'     && <FunnelSection client={client} accent={accent} />}
        {active === 'phases'     && <PhasesSection client={client} accent={accent} />}
        {active === 'market'     && <MarketSection client={client} accent={accent} />}
        {active === 'okrs'       && <OkrsSection client={client} accent={accent} />}
        {active === 'investment' && <InvestmentSection client={client} accent={accent} />}
        {active === 'debriefing' && <DebriefingSection client={client} accent={accent} />}
      </motion.div>
    </div>
  );
}

