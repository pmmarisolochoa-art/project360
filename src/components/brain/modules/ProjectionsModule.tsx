function midOfRange(s: string): number {
  const nums = s.match(/\d[\d.,]*/g)?.map((n) => Number(n.replace(/[.,]/g, ''))) ?? [];
  if (nums.length >= 2) return (nums[0] + nums[1]) / 2;
  if (nums.length === 1) return nums[0];
  return 0;
}

